import { build } from 'esbuild';
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
await mkdir('dist', { recursive: true });
await cp('public', 'dist', { recursive: true });
const bundle = await build({ entryPoints: ['src/main.ts'], outdir: 'dist/assets', entryNames: '[name]-[hash]', metafile: true, bundle: true, minify: true, target: 'es2022', format: 'esm' });
const js = '/' + Object.keys(bundle.metafile.outputs).find(file => file.endsWith('.js'))!.replace(/^dist\//, '');
const css = await readFile('public/style.css');
const cssUrl = `/assets/style-${createHash('sha256').update(css).digest('hex').slice(0, 12)}.css`;
await writeFile(`dist${cssUrl}`, css);
const html = (await readFile('public/index.html', 'utf8')).replace('/main.js', js).replace('/style.css', cssUrl);
await writeFile('dist/index.html', html);
const hash = createHash('sha256');
hash.update(html);
await build({ entryPoints: ['src/service-worker.ts'], outfile: 'dist/service-worker.js', bundle: true, minify: true, target: 'es2022', format: 'iife', define: { BUILD_ID: JSON.stringify(hash.digest('hex').slice(0, 12)), SHELL_ASSETS: JSON.stringify(['/', js, cssUrl, '/favicon-32x32.png']) } });
console.log('Built dist/');
